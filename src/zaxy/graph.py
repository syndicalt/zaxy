class GraphStore(ProjectionStore):
    """Async Neo4j wrapper for bi-temporal knowledge graph operations.

    Args:
        uri: Bolt URI, e.g. 'bolt://localhost:7687'.
        user: Neo4j username.
        password: Neo4j password.
    """

    def __init__(
        self,
        uri: str,
        user: str,
        password: str,
        ca_cert: str | None = None,
        trust_all: bool = False,
    ) -> None:
        self._uri = uri
        self._auth = (user, password)
        self._ca_cert = ca_cert
        self._trust_all = trust_all
        self._driver: Any | None = None
        self.last_projection_steps: tuple[str, ...] = ()

    async def connect(self) -> None:
        """Initialize the async driver with optional TLS."""
        async_graph_database, trust_all_cls, trust_custom_cas_cls = _load_async_neo4j()
        kwargs: dict[str, Any] = {"auth": self._auth}
        if self._trust_all:
            kwargs["encrypted"] = True
            kwargs["trusted_certificates"] = trust_all_cls()
        elif self._ca_cert:
            if not Path(self._ca_cert).exists():
                raise ValueError(
                    f"NEO4J_CA_CERT does not exist: {self._ca_cert}. "
                    "Unset NEO4J_CA_CERT for plain local bolt:// Neo4j or provide a valid CA file."
                )
            kwargs["encrypted"] = True
            kwargs["trusted_certificates"] = trust_custom_cas_cls(self._ca_cert)
        self._driver = async_graph_database.driver(self._uri, **kwargs)

    async def close(self) -> None:
        """Close the driver."""
        if self._driver:
            await self._driver.close()
            self._driver = None

    async def has_traversal_edges(self, session_id: str = "default") -> bool:
        """Return whether a session has active RELATES edges for traversal."""
        assert self._driver is not None, "Call connect() first"
        records, _, _ = await self._driver.execute_query(
            """
            MATCH (source:Entity {session_id: $session_id})-[r:RELATES]->(target:Entity {session_id: $session_id})
            WHERE r.valid_to IS NULL
              AND source.valid_to IS NULL
              AND target.valid_to IS NULL
            RETURN true AS has_edges
            LIMIT 1
            """,
            session_id=validate_session_id(session_id),
        )
        return bool(records)

    # ------------------------------------------------------------------
    # Schema
    # ------------------------------------------------------------------

    async def init_schema(self) -> None:
        """Create constraints and indexes idempotently.

        Must be called once before ingestion.
        """
        assert self._driver is not None, "Call connect() first"
        await apply_schema_migrations(self._driver)

    async def inspect_event_projection_status(
        self,
        session_id: str,
        *,
        eventloom_latest_seq: int | None = None,
        eventloom_latest_hash: str | None = None,
    ) -> GraphEventProjectionStatus:
        """Inspect Event nodes and hash-chain edges for one projected session."""
        assert self._driver is not None
        safe_session_id = validate_session_id(session_id)
        records, _, _ = await self._driver.execute_query(
            """
            MATCH (e:Event {session_id: $session_id})
            WITH count(e) AS event_count, max(e.seq) AS latest_seq
            OPTIONAL MATCH (latest:Event {session_id: $session_id, seq: latest_seq})
            WITH event_count, latest_seq, latest.hash AS latest_hash
            CALL () {
                MATCH (:Event {session_id: $session_id})-[n:NEXT_EVENT]->(:Event {session_id: $session_id})
                RETURN count(n) AS next_event_edges
            }
            CALL () {
                MATCH (:Event {session_id: $session_id})-[p:PREVIOUS_EVENT]->(:Event {session_id: $session_id})
                RETURN count(p) AS previous_event_edges
            }
            CALL () {
                MATCH (e:Event {session_id: $session_id})
                WHERE e.seq > 1
                OPTIONAL MATCH (prev:Event {session_id: $session_id, hash: e.prev_hash})
                OPTIONAL MATCH (prev)-[n:NEXT_EVENT]->(e)
                OPTIONAL MATCH (e)-[p:PREVIOUS_EVENT]->(prev)
                WITH e, prev, n, p
                WHERE prev IS NULL OR n IS NULL OR p IS NULL
                RETURN count(e) AS missing_chain_links
            }
            RETURN event_count,
                   latest_seq,
                   latest_hash,
                   next_event_edges,
                   previous_event_edges,
                   missing_chain_links
            """,
            session_id=safe_session_id,
        )
        record = records[0] if records else {}
        event_count = _int_record_value(record.get("event_count"))
        latest_seq = _optional_int_record_value(record.get("latest_seq"))
        latest_hash = _optional_str_record_value(record.get("latest_hash"))
        next_event_edges = _int_record_value(record.get("next_event_edges"))
        previous_event_edges = _int_record_value(record.get("previous_event_edges"))
        missing_chain_links = _int_record_value(record.get("missing_chain_links"))
        projection_lag = (
            max(0, eventloom_latest_seq - (latest_seq or 0))
            if eventloom_latest_seq is not None
            else None
        )
        latest_hash_matches = (
            latest_hash == eventloom_latest_hash
            if eventloom_latest_hash is not None
            else True
        )
        integrity_ok = (
            missing_chain_links == 0
            and latest_hash_matches
            and (projection_lag in (None, 0))
            and next_event_edges == max(0, event_count - 1)
            and previous_event_edges == max(0, event_count - 1)
        )
        return GraphEventProjectionStatus(
            session_id=safe_session_id,
            event_count=event_count,
            latest_seq=latest_seq,
            latest_hash=latest_hash,
            eventloom_latest_seq=eventloom_latest_seq,
            eventloom_latest_hash=eventloom_latest_hash,
            projection_lag=projection_lag,
            latest_hash_matches=latest_hash_matches,
            next_event_edges=next_event_edges,
            previous_event_edges=previous_event_edges,
            missing_chain_links=missing_chain_links,
            integrity_ok=integrity_ok,
        )

    async def inspect_inferred_edge_status(
        self,
        session_id: str,
        *,
        limit: int = 10,
    ) -> GraphInferredEdgeStatus:
        """Inspect inferred relationships by method, confidence, and evidence coverage."""
        assert self._driver is not None
        safe_session_id = validate_session_id(session_id)
        safe_limit = validate_limit(limit)
        method_records, _, _ = await self._driver.execute_query(
            """
            MATCH (:Entity)-[r:RELATES]->(:Entity)
            WHERE r.session_id = $session_id
              AND r.inferred = true
            WITH coalesce(r.inference_method, 'unknown') AS method,
                 r,
                 [key IN keys(r) WHERE key STARTS WITH 'evidence_'] AS evidence_keys
            WITH method,
                 count(r) AS edge_count,
                 collect(DISTINCT r.relation_type) AS relation_types,
                 avg(r.confidence) AS average_confidence,
                 min(r.confidence) AS minimum_confidence,
                 sum(CASE WHEN size(evidence_keys) > 0 THEN 1 ELSE 0 END) AS evidence_count,
                 sum(CASE WHEN size(evidence_keys) = 0 THEN 1 ELSE 0 END) AS missing_evidence_count,
                 sum(CASE
                     WHEN r.source_event_seq IS NULL OR r.source_event_hash IS NULL THEN 1
                     ELSE 0
                 END) AS missing_source_event_count
            RETURN method,
                   edge_count,
                   relation_types,
                   average_confidence,
                   minimum_confidence,
                   evidence_count,
                   missing_evidence_count,
                   missing_source_event_count
            ORDER BY edge_count DESC, method ASC
            """,
            session_id=safe_session_id,
        )
        sample_records, _, _ = await self._driver.execute_query(
            """
            MATCH (source:Entity)-[r:RELATES]->(target:Entity)
            WHERE r.session_id = $session_id
              AND r.inferred = true
            WITH source,
                 target,
                 r,
                 [key IN keys(r) WHERE key STARTS WITH 'evidence_'] AS evidence_keys
            RETURN source.name AS source,
                   target.name AS target,
                   r.relation_type AS relation_type,
                   r.confidence AS confidence,
                   coalesce(r.inference_method, 'unknown') AS method,
                   r.source_event_seq AS source_event_seq,
                   r.source_event_hash AS source_event_hash,
                   evidence_keys
            ORDER BY r.source_event_seq DESC, source.name ASC, target.name ASC
            LIMIT $limit
            """,
            session_id=safe_session_id,
            limit=safe_limit,
        )
        methods = tuple(_record_to_inferred_edge_method(record) for record in method_records)
        samples = tuple(_record_to_inferred_edge_sample(record) for record in sample_records)
        total_edges = sum(method.edge_count for method in methods)
        evidence_count = sum(method.evidence_count for method in methods)
        missing_evidence_count = sum(method.missing_evidence_count for method in methods)
        missing_source_event_count = sum(method.missing_source_event_count for method in methods)
        evidence_coverage = evidence_count / total_edges if total_edges else 1.0
        return GraphInferredEdgeStatus(
            session_id=safe_session_id,
            total_edges=total_edges,
            method_count=len(methods),
            evidence_count=evidence_count,
            missing_evidence_count=missing_evidence_count,
            missing_source_event_count=missing_source_event_count,
            evidence_coverage=evidence_coverage,
            methods=methods,
            samples=samples,
        )

