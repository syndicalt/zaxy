        assert self._driver is not None
        if limit <= 0:
            return []
        if not vector_has_signal(embedding):
            return []
        limit = validate_limit(limit)

        cypher = """
        CALL db.index.vector.queryNodes('entity_vector', $limit, $embedding)
        YIELD node, score
        """
