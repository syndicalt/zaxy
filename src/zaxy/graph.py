def _record_to_entity(node: Any) -> GraphEntity:
    """Convert a Neo4j node record to a GraphEntity."""
    props = dict(node)
    return GraphEntity(
        name=props.get("name", ""),
        entity_type=props.get("entity_type", ""),
        valid_from=str(props.get("valid_from", "")),
        valid_to=str(props.get("valid_to")) if props.get("valid_to") else None,
        session_id=props.get("session_id", "default"),
        properties={
            k: v
            for k, v in props.items()
            if k not in {"session_id", "name", "entity_type", "valid_from", "valid_to"}
        },
    )


def _record_to_inferred_edge_method(record: Any) -> GraphInferredEdgeMethodStatus:
    """Convert a Neo4j method aggregate into an inferred-edge status row."""
    relation_types = record.get("relation_types") or []
    safe_relation_types = sorted(str(value) for value in relation_types if value is not None)
    return GraphInferredEdgeMethodStatus(
        method=str(record.get("method") or "unknown"),
        edge_count=_int_record_value(record.get("edge_count")),
        relation_types=tuple(safe_relation_types),
        average_confidence=_optional_float_record_value(record.get("average_confidence")),
        minimum_confidence=_optional_float_record_value(record.get("minimum_confidence")),
        evidence_count=_int_record_value(record.get("evidence_count")),
        missing_evidence_count=_int_record_value(record.get("missing_evidence_count")),
        missing_source_event_count=_int_record_value(record.get("missing_source_event_count")),
    )


def _record_to_inferred_edge_sample(record: Any) -> GraphInferredEdgeSample:
    """Convert a Neo4j inferred relationship record into an audit sample."""
    evidence_keys = record.get("evidence_keys") or []
    safe_evidence_keys = sorted(str(value) for value in evidence_keys if value is not None)
    return GraphInferredEdgeSample(
        source=str(record.get("source") or ""),
        target=str(record.get("target") or ""),
        relation_type=str(record.get("relation_type") or ""),
        confidence=_optional_float_record_value(record.get("confidence")),
        method=str(record.get("method") or "unknown"),
        source_event_seq=_optional_int_record_value(record.get("source_event_seq")),
        source_event_hash=_optional_str_record_value(record.get("source_event_hash")),
        evidence_keys=tuple(safe_evidence_keys),
    )


def _traversal_inferred_metadata(record: Any) -> dict[str, Any]:
    """Return normalized inferred-edge trust metadata for a traversal path."""
    inferred_flags = [flag is True for flag in record.get("path_inferred_flags") or []]
    inferred_edge_count = sum(1 for flag in inferred_flags if flag)
    if inferred_edge_count == 0:
        return {}
    evidence_counts = [
        value
        for value in (_int_record_value(raw) for raw in record.get("path_inferred_evidence_counts") or [])
        if value > 0
    ]
    return {
        "_path_inferred_edge_count": inferred_edge_count,
        "_path_inferred_confidences": [
            value
            for value in (
                _optional_float_record_value(raw)
                for raw in record.get("path_inferred_confidences") or []
            )
            if value is not None
        ],
        "_path_inference_methods": [
            str(method)
            for method in record.get("path_inference_methods") or []
            if isinstance(method, str) and method
        ],
        "_path_inferred_source_event_count": len(record.get("path_inferred_source_event_refs") or []),
        "_path_inferred_evidence_count": sum(evidence_counts),
        "_path_inferred_evidenced_edge_count": len(evidence_counts),
    }


def _int_record_value(value: Any) -> int:
    if isinstance(value, int):
        return value
    return 0


def _optional_int_record_value(value: Any) -> int | None:
    if isinstance(value, int):
        return value
    return None


def _optional_str_record_value(value: Any) -> str | None:
    if isinstance(value, str):
        return value
    return None


def _optional_float_record_value(value: Any) -> float | None:
    if isinstance(value, bool):
        return None
    if isinstance(value, int | float):
        return float(value)
    return None


def _neo4j_properties(properties: dict[str, Any] | None) -> dict[str, _Neo4jPropertyValue]:
    """Filter extracted properties to values accepted by Neo4j node properties."""
    if not properties:
        return {}
    safe_properties: dict[str, _Neo4jPropertyValue] = {}
    for key, value in properties.items():
        if not _is_neo4j_property_value(value):
            continue
        safe_key = f"payload_{key}" if key in _ENTITY_STORAGE_PROPERTIES else key
        safe_properties[safe_key] = value
    return safe_properties


def _edge_evidence_properties(evidence: dict[str, Any] | None) -> dict[str, _Neo4jPropertyValue]:
    """Normalize flat inferred-edge evidence into namespaced relationship properties."""
    if not evidence:
        return {}
    safe_properties: dict[str, _Neo4jPropertyValue] = {}
    for key, value in evidence.items():
        if not _PROPERTY_KEY_RE.fullmatch(key):
            continue
        if not _is_neo4j_property_value(value):
            continue
        safe_properties[f"evidence_{key}"] = value
    return safe_properties


def _source_citation_properties(properties: dict[str, Any] | None) -> dict[str, Any]:
    """Normalize source citation fields for first-class graph projections."""
    if not properties:
        return {
            "source_path": None,
            "source_start_line": None,
            "source_end_line": None,
            "source_sha256": None,
        }
    source_path = properties.get("source_path")
    return {
        "source_path": source_path if isinstance(source_path, str) and source_path else None,
        "source_start_line": _optional_positive_int(properties.get("source_start_line")),
        "source_end_line": _optional_positive_int(properties.get("source_end_line")),
        "source_sha256": _optional_text_property(properties.get("source_sha256")),
    }


def _optional_positive_int(value: Any) -> int | None:
    """Return a positive integer property, otherwise None."""
    if isinstance(value, int) and not isinstance(value, bool) and value > 0:
        return value
    return None


def _optional_text_property(value: Any) -> str | None:
    """Return non-empty string property, otherwise None."""
    if not isinstance(value, str):
        return None
    text = value.strip()
    return text or None


def _extraction_observed_at(result: ExtractionResult) -> str | None:
    """Return the earliest available event timestamp carried by an extraction."""
    values = [entity.observed_at for entity in result.entities]
    values.extend(edge.valid_from for edge in result.edges)
    return min(values) if values else None


def _retired_source_path(result: ExtractionResult) -> str | None:
    """Return the source path targeted by a projection retirement event."""
    for entity in result.entities:
        source_path = entity.properties.get("source_path") if entity.properties else None
        if isinstance(source_path, str) and source_path:
            return source_path
    return None


def _typed_relationship_label(relation_type: str) -> str:
    """Convert a safe extractor relation type into a Neo4j relationship label."""
    if not _RELATION_TYPE_RE.fullmatch(relation_type):
        raise ValueError(f"Invalid relation_type for typed relationship label: {relation_type!r}")
    return relation_type.upper()


def _is_neo4j_property_value(value: Any) -> bool:
    """Return whether a value is a Neo4j scalar or scalar list."""
    if value is None:
        return False
    if isinstance(value, str | int | float | bool):
        return True
    if not isinstance(value, list):
        return False
    return all(isinstance(item, str | int | float | bool) for item in value)
